function icon(name, cls) {
  var body = ICONS[name];
  if (!body) return "";
  return '<svg class="icon' + (cls ? " " + cls : "") + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' + body + "</svg>";
}

/* Fill every <span data-icon="name"> under root that has not been filled yet. */
function hydrateIcons(root) {
  var nodes = (root || document).querySelectorAll("[data-icon]");
  for (var i = 0; i < nodes.length; i++) {
    var node = nodes[i];
    if (node.getAttribute("data-icon-ready") === node.getAttribute("data-icon")) continue;
    node.innerHTML = icon(node.getAttribute("data-icon"));
    node.setAttribute("data-icon-ready", node.getAttribute("data-icon"));
    node.classList.add("icon-wrap");
  }
}
